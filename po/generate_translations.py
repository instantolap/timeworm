def generate_po(lang_code, lang_data):
    """Generate a .po file for a language."""
    lines = [
        f"# TimeWorm {lang_data['lang']} Translation",
        "# Copyright (C) 2026 TBE",
        "#",
        'msgid ""',
        'msgstr ""',
        '"Project-Id-Version: TimeWorm 1.0\\n"',
        '"PO-Revision-Date: 2026-02-22 19:00+0100\\n"',
        '"Last-Translator: Thomas Behrends\\n"',
        f'"Language: {lang_code}\\n"',
        '"MIME-Version: 1.0\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Content-Transfer-Encoding: 8bit\\n"',
        "",
    ]
    for msgid, msgstr in lang_data["strings"].items():
        lines.append(f'msgid "{msgid}"')
        lines.append(f'msgstr "{msgstr}"')
        lines.append("")

    po_path = PO_DIR / f"{lang_code}.po"
    po_path.write_text("\n".join(lines), encoding="utf-8")
    return po_path


def compile_mo(lang_code, po_path):
    """Compile .po to .mo using babel."""
    from babel.messages.mofile import write_mo
    from babel.messages.pofile import read_po

    mo_dir = LOCALE_DIR / lang_code / "LC_MESSAGES"
    mo_dir.mkdir(parents=True, exist_ok=True)
    mo_path = mo_dir / "timeworm.mo"

    with open(po_path, "r", encoding="utf-8") as f:
        catalog = read_po(f)
    with open(mo_path, "wb") as f:
        write_mo(f, catalog)

    return mo_path, len(catalog)


